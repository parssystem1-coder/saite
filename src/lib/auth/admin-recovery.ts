import { SITE } from '@/lib/constants'

/**
 * بازیابی دسترسی مدیر.
 *
 * ══════════════════════════════════════════════════════════════
 *  چرا این مسیر با «فراموشی رمز» مشتری فرق دارد
 * ══════════════════════════════════════════════════════════════
 *
 * وسوسه‌انگیز است که همان فرم مشتری را کپی کنیم: ایمیل بگیریم و
 * لینک بازیابی بفرستیم. اما برای حساب مدیر این **الگوی خطرناکی**
 * است، چون:
 *
 *  ۱. **صندوق ایمیل تبدیل به کلید پنل می‌شود.** اگر ایمیل مدیر
 *     هک شود، مهاجم با یک کلیک کل فروشگاه را می‌گیرد. برای حساب
 *     مشتری این ریسک قابل قبول است؛ برای حساب مدیر نه.
 *
 *  ۲. **سطح حمله را بزرگ می‌کند.** یک endpoint عمومی که ایمیل
 *     می‌پذیرد و توکن پرقدرت صادر می‌کند، هدف جذابی است — به‌ویژه
 *     در برابر حملات SSRF، تزریق هدر و مسمومیت host header.
 *
 *  ۳. **مدیر معمولاً یک نفر است، نه هزاران نفر.** بازیابی خودکار
 *     برای مقیاس طراحی می‌شود؛ اینجا مقیاسی وجود ندارد.
 *
 * ── رویکرد انتخاب‌شده: بازیابی خارج از باند (out-of-band) ─────
 * به‌جای فرم خودکار، مسیر انسانی و قابل حسابرسی:
 *   • مدیر دیگری از پنل رمز را بازنشانی کند (سریع‌ترین راه)
 *   • یا تماس با پشتیبانی فنی و احراز هویت انسانی
 *
 * این همان کاری است که پنل‌های مدیریتی جدی (WordPress با
 * WP-CLI، cPanel، پنل‌های بانکی) انجام می‌دهند.
 *
 * ── فاز بک‌اند ────────────────────────────────────────────────
 * وقتی چند مدیر داشتید، این گزینه‌ها اضافه شوند:
 *   • بازنشانی توسط مدیر ارشد از «تنظیمات ← کاربران»
 *   • کد بازیابی یک‌بارمصرف که هنگام ساخت حساب چاپ می‌شود
 *   • احراز هویت دومرحله‌ای (TOTP) با کدهای پشتیبان
 *   • دستور CLI روی سرور برای شرایط اضطراری
 * هر بازنشانی باید در لاگ حسابرسی ثبت شود.
 */

export interface RecoveryOption {
  /** عنوان کوتاه راه‌حل */
  title: string
  /** توضیح اینکه چه زمانی از این راه استفاده شود */
  description: string
  /** نام آیکون lucide */
  icon: 'users' | 'phone' | 'shield'
  /** اگر کنش مستقیمی دارد */
  action?: { label: string; href: string; external?: boolean }
}

export function getAdminRecoveryOptions(): RecoveryOption[] {
  return [
    {
      title: 'از مدیر دیگری کمک بگیرید',
      description:
        'اگر مدیر دیگری به پنل دسترسی دارد، می‌تواند از «تنظیمات ← حساب مدیر» رمز شما را بازنشانی کند. سریع‌ترین راه همین است.',
      icon: 'users',
    },
    {
      title: 'تماس با پشتیبانی فنی',
      description:
        'اگر تنها مدیر سیستم هستید، با تیم فنی تماس بگیرید. هویت شما به‌صورت انسانی بررسی و رمز جدید صادر می‌شود.',
      icon: 'phone',
      action: {
        label: SITE.phone,
        href: `tel:${SITE.phoneLtr}`,
      },
    },
    {
      title: 'چرا بازیابی خودکار نداریم؟',
      description:
        'لینک بازیابی ایمیلی یعنی هر کس صندوق ایمیل شما را در اختیار بگیرد، کل فروشگاه را می‌گیرد. برای حساب مدیر، بررسی انسانی امن‌تر است.',
      icon: 'shield',
    },
  ]
}
