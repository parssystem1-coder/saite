/**
 * بازیابی دسترسی مدیر.
 *
 * ══════════════════════════════════════════════════════════════
 *  چرا این مسیر با «فراموشی رمز» مشتری فرق دارد
 * ══════════════════════════════════════════════════════════════
 *
 * وسوسه‌انگیز است که همان فرم مشتری را کپی کنیم: ایمیل بگیریم و
 * لینک بازیابی بفرستیم. اما برای حساب مدیر این **الگوی خطرناکی**
 * است، چون صندوق ایمیل تبدیل به کلید کل فروشگاه می‌شود: اگر
 * ایمیل مدیر هک شود، مهاجم با یک کلیک همه‌چیز را می‌گیرد.
 *
 * ── دو وضعیت متفاوت ───────────────────────────────────────────
 *
 * ۱. **فاز فعلی (بدون بک‌اند)** — اعتبارنامه در کد یا `.env.local`
 *    است، نه در دیتابیس. پس «فراموشی» عملاً بن‌بست نیست: کافی
 *    است فایل را باز کنید. راهنمای گام‌به‌گام در UI نمایش داده
 *    می‌شود. این حالت مخصوص توسعه‌دهنده‌ای است که تنها مدیر
 *    سایت خودش هم هست.
 *
 * ۲. **پس از اتصال بک‌اند** — رمز هش‌شده در دیتابیس است و از روی
 *    فایل قابل خواندن نیست. آن‌وقت گزینه‌های زیر لازم می‌شوند.
 */

export interface RecoveryOption {
  /** عنوان کوتاه راه‌حل */
  title: string
  /** توضیح اینکه چه زمانی از این راه استفاده شود */
  description: string
  /** نام آیکون lucide */
  icon: 'terminal' | 'file' | 'users' | 'phone' | 'shield'
  /** دستور یا مسیری که کاربر باید اجرا/باز کند */
  code?: string
  /** اگر کنش مستقیمی دارد */
  action?: { label: string; href: string }
}

